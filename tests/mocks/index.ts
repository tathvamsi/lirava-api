export function seedTestCorpus(
  db: MockDatabase,
  qdrant: MockQdrantClient,
  collectionName = "soli_legal_corpus",
): void {
  // 1. Seed provisions into PostgreSQL mock
  for (const p of CANONICAL_BARE_ACT_PROVISIONS) {
    db.legalProvisions.set(p.id, {
      ...p,
      created_at: Date.now(),
      indexed_at: Date.now(),
    });
  }

  // 2. Seed landmark cases into PostgreSQL mock
  for (const c of CANONICAL_LANDMARK_CASES) {
    db.legalCases.set(c.id, {
      ...c,
      created_at: Date.now(),
    });
  }

  // 3. Upsert provisions into Qdrant mock
  const points = CANONICAL_BARE_ACT_PROVISIONS.map((item, index) => {
    const textToEmbed = `${item.act} - ${item.section}: ${item.title}\n${item.text}\nRatio: ${item.ratio || ""}\nSource: ${item.source}`;
    const vector = generateDeterministicVector(textToEmbed, 1024);

    return {
      id: index + 1,
      vector,
      payload: {
        act: item.act,
        act_code: item.act_code,
        section: item.section,
        section_num: item.section_num,
        title: item.title,
        text: item.text,
        statutoryText: item.text,
        ratio: item.ratio,
        source: item.source,
        year: item.year,
        category: item.category,
      },
    };
  });

  // 4. Upsert cases into Qdrant mock
  const casePoints = CANONICAL_LANDMARK_CASES.map((item, index) => {
    const textToEmbed = `${item.court} - ${item.case_title} (${item.primary_citation} / ${item.neutral_citation}): ${item.ratio}\nPrinciples: ${(item.principles || []).join(" ")}`;
    const vector = generateDeterministicVector(textToEmbed, 1024);

    return {
      id: 5000 + index + 1,
      vector,
      payload: {
        act: item.court,
        section: item.primary_citation,
        title: item.case_title,
        text: item.ratio,
        statutoryText: item.ratio,
        ratio: item.ratio,
        court: item.court,
        year: item.year,
        neutral_citation: item.neutral_citation,
        category: item.category,
        source: `Judicial Citation: ${item.primary_citation}`,
      },
    };
  });

  qdrant.upsert(collectionName, { points: [...points, ...casePoints] });
}

export function setupTestHarness(): { mockDb: MockDatabase; mockQdrant: MockQdrantClient } {
  resetMockDb();
  resetMockQdrant();
  const mockDb = getMockDatabase();
  const mockQdrant = getMockQdrant();

  setSql(createMockSql(mockDb));
  setQdrant(mockQdrant as any);
  setupMockEmbeddingsFetch();

  seedTestCorpus(mockDb, mockQdrant);

  return { mockDb, mockQdrant };
}
